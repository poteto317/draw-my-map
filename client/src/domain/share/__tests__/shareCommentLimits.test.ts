import {
  SHARE_COMMENT_AUTHOR_NAME_MAX_CODE_POINTS,
  SHARE_COMMENT_BODY_MAX_LENGTH,
  SHARE_COMMENT_BODY_RAW_MAX_LENGTH,
  SHARE_COMMENT_MAX_BODY_BYTES,
  SHARE_COMMENT_MAX_COMMENTS_PER_MAP,
  SHARE_COMMENT_MAX_COMMENTS_PER_THREAD,
  SHARE_COMMENT_MAX_THREADS_PER_MAP,
  SHARE_COMMENT_NODE_LABEL_SNAPSHOT_MAX_CODE_POINTS,
} from "@/domain/share/shareCommentLimits";

describe("shareCommentLimits", () => {
  it("設計 §5 の上限値", () => {
    expect(SHARE_COMMENT_BODY_MAX_LENGTH).toBe(2000);
    expect(SHARE_COMMENT_BODY_RAW_MAX_LENGTH).toBe(SHARE_COMMENT_BODY_MAX_LENGTH * 4);
    expect(SHARE_COMMENT_AUTHOR_NAME_MAX_CODE_POINTS).toBe(50);
    expect(SHARE_COMMENT_NODE_LABEL_SNAPSHOT_MAX_CODE_POINTS).toBe(80);
    expect(SHARE_COMMENT_MAX_THREADS_PER_MAP).toBe(200);
    expect(SHARE_COMMENT_MAX_COMMENTS_PER_MAP).toBe(1000);
    expect(SHARE_COMMENT_MAX_COMMENTS_PER_THREAD).toBe(50);
    expect(SHARE_COMMENT_MAX_BODY_BYTES).toBe(16 * 1024);
  });
});
